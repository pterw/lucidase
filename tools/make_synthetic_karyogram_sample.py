"""Write the deterministic SYNTHETIC karyogram demo sample (contract K-C5).

Output: web/demo-data/sample-karyogram-23andme.txt. It holds every data row of
web/demo-data/sample-23andme.txt plus 15,000 randomly placed background markers, so the
karyogram's density view has something to show. Geometry comes from the knowledge base
`assemblies` section (GRCh37); no length or band is hard-coded here. Stdlib only.

Usage: python tools/make_synthetic_karyogram_sample.py
"""

import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KB_PATH = ROOT / "web" / "src" / "knowledge-base.json"
ORIGINAL_PATH = ROOT / "web" / "demo-data" / "sample-23andme.txt"
OUTPUT_PATH = ROOT / "web" / "demo-data" / "sample-karyogram-23andme.txt"

SEED = 20261003
BACKGROUND_TOTAL = 15_000
LOCUS_MARGIN_BP = 1_000
ACROCENTRIC = ("13", "14", "15", "21", "22")
# Y gets no markers: the demo's sex QC must keep reading "two X chromosomes".
BACKGROUND_CHROMS = tuple(str(n) for n in range(1, 23)) + ("X",)
CHROM_ORDER = BACKGROUND_CHROMS + ("Y", "MT")
ALLELE_PAIRS = (("A", "G"), ("C", "T"), ("A", "C"), ("G", "T"))
P_HOM_REF = 0.5
P_HET = 0.3  # the remaining 0.2 is hom-alt

BANNER = [
    "# " + "=" * 78,
    "# SYNTHETIC DEMO DATASET - FOR RESEARCH, TESTING, AND DEMONSTRATION ONLY",
    "# This file holds 15,000 randomly placed background markers plus every data row",
    "# of sample-23andme.txt. It is NOT from a real individual and contains no",
    "# protected health information (PHI).",
    "# Generated by tools/make_synthetic_karyogram_sample.py (fixed seed).",
    "# " + "=" * 78,
]


def load_kb():
    return json.loads(KB_PATH.read_text(encoding="utf-8"))


def allocate(chromosomes, total=BACKGROUND_TOTAL):
    """Largest-remainder split of `total` across BACKGROUND_CHROMS by GRCh37 length."""
    lengths = {c: chromosomes[c]["length"] for c in BACKGROUND_CHROMS}
    whole = sum(lengths.values())
    quotas = {c: total * n / whole for c, n in lengths.items()}
    counts = {c: int(q) for c, q in quotas.items()}
    leftover = total - sum(counts.values())
    by_remainder = sorted(BACKGROUND_CHROMS, key=lambda c: (-(quotas[c] - counts[c]), BACKGROUND_CHROMS.index(c)))
    for c in by_remainder[:leftover]:
        counts[c] += 1
    return counts


def allowed_interval(chrom, info):
    """The [lo, hi] range of positions allowed before the centromere is cut out."""
    cen_start, cen_end = info["centromere"]
    if chrom in ACROCENTRIC:
        return [(cen_end + 1, info["length"])]
    return [(1, cen_start - 1), (cen_end + 1, info["length"])]


def original_lines():
    text = ORIGINAL_PATH.read_text(encoding="utf-8")
    return text.replace("\r\n", "\n").split("\n")


def genotype(rng, pair):
    r = rng.random()
    if r < P_HOM_REF:
        return pair[0] * 2
    if r < P_HOM_REF + P_HET:
        return pair[0] + pair[1]
    return pair[1] * 2


def build_sample_text():
    kb = load_kb()
    chromosomes = kb["assemblies"]["GRCh37"]["chromosomes"]
    counts = allocate(chromosomes)

    lines = original_lines()
    header = [l for l in lines if l.startswith("# This data file") or l.strip() == "# build 37"]
    column_header = next(l for l in lines if l.startswith("# rsid"))
    original_rows = [l for l in lines if l and not l.startswith("#")]

    taken = {}  # chrom -> set of positions already used (original rows, then background)
    original = []
    for row in original_rows:
        rsid, chrom, pos, geno = row.split("\t")
        taken.setdefault(chrom, set()).add(int(pos))
        original.append((chrom, int(pos), row))
    loci = {}
    for locus in kb["loci"].values():
        loci.setdefault(locus["chrom"], []).append(locus["pos_grch37"])

    rng = random.Random(SEED)
    background = []
    for chrom in BACKGROUND_CHROMS:
        intervals = allowed_interval(chrom, chromosomes[chrom])
        sizes = [hi - lo + 1 for lo, hi in intervals]
        used = taken.setdefault(chrom, set())
        near = loci.get(chrom, [])
        for _ in range(counts[chrom]):
            while True:
                k = rng.randrange(sum(sizes))
                for (lo, _hi), size in zip(intervals, sizes):
                    if k < size:
                        pos = lo + k
                        break
                    k -= size
                if pos in used or any(abs(pos - p) <= LOCUS_MARGIN_BP for p in near):
                    continue
                break
            used.add(pos)
            pair = ALLELE_PAIRS[rng.randrange(len(ALLELE_PAIRS))]
            background.append((chrom, pos, genotype(rng, pair)))
    background.sort(key=lambda t: (CHROM_ORDER.index(t[0]), t[1]))

    rows = [(CHROM_ORDER.index(c), p, 0, row) for c, p, row in original]
    rows += [(CHROM_ORDER.index(c), p, 1, (c, g)) for c, p, g in background]
    rows.sort(key=lambda t: (t[0], t[1]))
    out = []
    n = 0
    for _o, p, kind, payload in rows:
        if kind == 0:
            out.append(payload)
        else:
            n += 1
            out.append(f"i9{n:07d}\t{payload[0]}\t{p}\t{payload[1]}")
    return "\n".join(BANNER + header + [column_header] + out) + "\n"


def main():
    OUTPUT_PATH.write_bytes(build_sample_text().encode("utf-8"))
    print(f"wrote {OUTPUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
