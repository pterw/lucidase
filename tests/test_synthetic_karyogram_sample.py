"""Tests for the deterministic synthetic karyogram sample (contract K-C5)."""

import json
import re

import pytest

from tools import make_synthetic_karyogram_sample as gen

KB = json.loads(gen.KB_PATH.read_text(encoding="utf-8"))
CHROMS = KB["assemblies"]["GRCh37"]["chromosomes"]


def _rows(text):
    return [l.split("\t") for l in text.split("\n") if l and not l.startswith("#")]


def _committed():
    return gen.OUTPUT_PATH.read_bytes().decode("utf-8").replace("\r\n", "\n")


def _original_rows():
    text = gen.ORIGINAL_PATH.read_bytes().decode("utf-8").replace("\r\n", "\n")
    return [l for l in text.split("\n") if l and not l.startswith("#")]


def _background():
    return [r for r in _rows(_committed()) if r[0].startswith("i9")]


def _first_difference(generated, committed):
    """A short description of where two texts first differ (pytest would diff 370 KB for minutes)."""
    a, b = generated.split("\n"), committed.split("\n")
    for i in range(max(len(a), len(b))):
        la = a[i] if i < len(a) else "<end of text>"
        lb = b[i] if i < len(b) else "<end of text>"
        if la != lb:
            return f"line {i + 1}: generated {la!r} != committed {lb!r}"
    return "no difference"


def test_regenerating_in_memory_equals_the_committed_file():
    generated, committed = gen.build_sample_text(), _committed()
    same = generated == committed  # a bool, so a failure never renders 370 KB
    assert same, (
        "committed sample is stale (run tools/make_synthetic_karyogram_sample.py); first difference at "
        + _first_difference(generated, committed)
    )


def test_first_difference_names_the_line_and_both_texts():
    assert _first_difference("a\nb\nc", "a\nX\nc") == "line 2: generated 'b' != committed 'X'"
    assert _first_difference("a", "a\nb") == "line 2: generated '<end of text>' != committed 'b'"


def test_rows_are_the_original_rows_plus_exactly_15000_background_rows():
    lines = [l for l in _committed().split("\n") if l and not l.startswith("#")]
    kept = [l for l in lines if not l.startswith("i9")]
    assert sorted(kept) == sorted(_original_rows())  # verbatim; the file is position-sorted
    assert len(lines) - len(kept) == 15_000
    assert [r[0] for r in _background()] == [f"i9{n:07d}" for n in range(1, 15_001)]
    assert "\r" not in gen.build_sample_text()  # generated text, not the autocrlf-dependent checkout


def test_background_positions_obey_the_allowed_position_rules():
    original = {(r.split("\t")[1], int(r.split("\t")[2])) for r in _original_rows()}
    loci = {}
    for locus in KB["loci"].values():
        loci.setdefault(locus["chrom"], []).append(locus["pos_grch37"])
    seen = set()
    for _id, chrom, pos, geno in _background():
        pos = int(pos)
        info = CHROMS[chrom]  # Y and MT would KeyError or fail below
        assert chrom != "Y"
        assert 1 <= pos <= info["length"]
        assert not info["centromere"][0] <= pos <= info["centromere"][1]
        if chrom in ("13", "14", "15", "21", "22"):
            assert pos > info["centromere"][1]
        assert all(abs(pos - p) > 1_000 for p in loci.get(chrom, []))
        assert (chrom, pos) not in original
        assert (chrom, pos) not in seen
        seen.add((chrom, pos))
        assert re.fullmatch(r"[ACGT]{2}", geno)


EXPECTED_ALLOCATION = {
    "1": 1231, "2": 1202, "3": 978, "4": 944, "5": 894, "6": 845, "7": 786, "8": 723, "9": 698, "10": 670,
    "11": 667, "12": 661, "13": 569, "14": 530, "15": 507, "16": 446, "17": 401, "18": 386, "19": 292,
    "20": 311, "21": 238, "22": 254, "X": 767,
}  # largest remainder: 15,000 * GRCh37 length / total length, leftover units to the biggest fractions


def test_per_chromosome_counts_match_largest_remainder_allocation():
    counts = gen.allocate(CHROMS)
    assert counts == EXPECTED_ALLOCATION
    assert sum(counts.values()) == 15_000
    actual = {}
    for _id, chrom, _pos, _g in _background():
        actual[chrom] = actual.get(chrom, 0) + 1
    assert actual == counts


def test_missing_header_lines_raise_instead_of_being_skipped():
    assert gen.select_header(["# This data file generated by X", "# build 37"]) == [
        "# This data file generated by X",
        "# build 37",
    ]
    with pytest.raises(ValueError, match="build 37"):
        gen.select_header(["# This data file generated by X"])
    with pytest.raises(ValueError, match="This data file"):
        gen.select_header(["# build 37"])


def test_rows_are_sorted_by_chromosome_order_then_position():
    order = gen.CHROM_ORDER
    keys = [(order.index(r[1]), int(r[2])) for r in _rows(_committed())]
    assert keys == sorted(keys)


def _build_from(monkeypatch, lines):
    monkeypatch.setattr(gen, "original_lines", lambda: lines)
    return gen.build_sample_text()


def _good_original():
    return gen.original_lines()


def test_missing_column_header_raises_a_named_error_not_stopiteration(monkeypatch):
    lines = [l for l in _good_original() if not l.startswith("# rsid")]
    with pytest.raises(gen.SampleInputError, match="column header"):
        _build_from(monkeypatch, lines)


@pytest.mark.parametrize(
    "bad_row, message",
    [
        ("rs1\t1\t100", "4 tab-separated fields"),
        ("rs1\t1\tabc\tAA", "position"),
        ("rs1	1	0	AA", "position"),
        ("rs1\tZZ\t100\tAA", "chromosome"),
    ],
)
def test_malformed_original_row_raises_a_named_error(monkeypatch, bad_row, message):
    with pytest.raises(gen.SampleInputError, match=message):
        _build_from(monkeypatch, _good_original() + [bad_row])


def test_sample_input_error_is_a_value_error():
    assert issubclass(gen.SampleInputError, ValueError)
