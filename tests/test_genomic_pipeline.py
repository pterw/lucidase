    def test_variant_annotation_clinvar_and_hpa(self):
        variants, _ = GenomicParser.parse_text(self.sample_23andme)
        annotator = VariantAnnotator()
        records = annotator.annotate_genome(variants)

        self.assertGreater(len(records), 5)
        # Top record should be synthesized APOE-STATUS (magnitude 6.0, Bad)
        top = records[0]
        self.assertEqual(top.rsid, "APOE-STATUS")
        self.assertEqual(top.gene, "APOE")
        self.assertEqual(top.magnitude, 6.0)
        self.assertEqual(top.repute, "Bad")
        self.assertEqual(top.review_stars, 4)

        # Check Human Protein Atlas integration
        self.assertIn("liver", top.hpa_tissues)
        self.assertEqual(top.hpa_tissues["liver"], "High")
        self.assertIn("Secreted", top.hpa_subcellular)

        # Check individual rs429358 call
        rs429_rec = next(r for r in records if r.rsid == "rs429358")
        self.assertEqual(rs429_rec.magnitude, 5.0)

        # Check HFE C282Y carrier (rs1800562 AG)
        hfe_rec = next(r for r in records if r.rsid == "rs1800562")
        self.assertEqual(hfe_rec.gene, "HFE")
        self.assertTrue(hfe_rec.acmg_actionable)
        self.assertEqual(hfe_rec.category, "Carrier")
        self.assertEqual(hfe_rec.review_stars, 4)
        self.assertIn("duodenum", hfe_rec.hpa_tissues)
        self.assertEqual(hfe_rec.hpa_tissues["duodenum"], "High")

        # Check Pharmacogenomics: CYP2C19 *2 carrier (rs4244285 AG)
        cyp_rec = next(r for r in records if r.rsid == "rs4244285")
        self.assertEqual(cyp_rec.category, "Pharmacogenomics")
        self.assertIn("Clopidogrel", cyp_rec.drug_response)
        self.assertIn("Endoplasmic reticulum membrane", cyp_rec.hpa_subcellular)

        # Check CFTR deltaF508 carrier (DI)
        cftr_rec = next(r for r in records if r.rsid == "rs113993960")
        self.assertEqual(cftr_rec.category, "Carrier")
        self.assertEqual(cftr_rec.gene, "CFTR")

