        self.assertEqual(sim_carrier["p_carrier_genotype"], 0.50)

        sim_wt = engine.simulate_offspring_pedigree("CFTR", "DI", partner_status="wildtype")
        self.assertEqual(sim_wt["p_affected_genotype"], 0.0)
        self.assertEqual(sim_wt["p_carrier_genotype"], 0.50)

