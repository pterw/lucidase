_KB_JSON = None


def pipeline_kb_json() -> dict:
    """The KB the pipeline builds from its curation, in memory (never the committed file)."""
    global _KB_JSON
    if _KB_JSON is None:
        kb, errors = build_kb(copy.deepcopy(load_curation()))
        assert errors == [], errors
        _KB_JSON = kb
    return copy.deepcopy(_KB_JSON)


def make_annotator() -> VariantAnnotator:
    return VariantAnnotator(kb=validate_kb(pipeline_kb_json()))


