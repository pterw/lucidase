    def test_apoe_diplotype_resolution(self):
        annotator = VariantAnnotator()

        # Case 1: APOE e3/e3 (TT + CC) -> Normal Baseline
        v_e3e3 = {
            "rs429358": VariantCall("rs429358", "19", 45411941, "TT", zygosity="hom"),
            "rs7412": VariantCall("rs7412", "19", 45412079, "CC", zygosity="hom"),
        }
        rec, info = annotator.resolve_apoe_diplotype(v_e3e3)
        self.assertIsNotNone(rec)
        self.assertEqual(info["diplotype"], "ε3/ε3")
        self.assertEqual(rec.category, "Carrier")
        self.assertIn("1.0×", info["risk_ratio"])

        # Case 2: APOE e3/e4 Carrier (CT + CC) -> Elevated Alzheimer's Risk
        v_e3e4 = {
            "rs429358": VariantCall("rs429358", "19", 45411941, "CT", zygosity="het"),
            "rs7412": VariantCall("rs7412", "19", 45412079, "CC", zygosity="hom"),
        }
        rec, info = annotator.resolve_apoe_diplotype(v_e3e4)
        self.assertIsNotNone(rec)
        self.assertEqual(info["diplotype"], "ε3/ε4")
        self.assertEqual(rec.category, "Carrier")
        self.assertIn("3–4×", info["risk_ratio"])

        # Case 3: APOE e2/e3 Carrier (TT + CT) -> Protective
        v_e2e3 = {
            "rs429358": VariantCall("rs429358", "19", 45411941, "TT", zygosity="hom"),
            "rs7412": VariantCall("rs7412", "19", 45412079, "CT", zygosity="het"),
        }
        rec, info = annotator.resolve_apoe_diplotype(v_e2e3)
        self.assertEqual(info["diplotype"], "ε2/ε3")
        self.assertEqual(rec.category, "Carrier")
        self.assertIn("Protective", info["risk_ratio"])

        # Case 4: Minus-strand genotype calls (e.g. 23andMe reverse strand: AA + GG -> e3/e3)
        v_rev = {
            "rs429358": VariantCall("rs429358", "19", 45411941, "AA", zygosity="hom"),
            "rs7412": VariantCall("rs7412", "19", 45412079, "GG", zygosity="hom"),
        }
        rec, info = annotator.resolve_apoe_diplotype(v_rev)
        self.assertEqual(info["diplotype"], "ε3/ε3")
        self.assertEqual(rec.category, "Carrier")

        # Case 5: Minus-strand e3/e4 Carrier (AG + GG -> e3/e4)
        v_rev_e4 = {
            "rs429358": VariantCall("rs429358", "19", 45411941, "AG", zygosity="het"),
            "rs7412": VariantCall("rs7412", "19", 45412079, "GG", zygosity="hom"),
        }
        rec, info = annotator.resolve_apoe_diplotype(v_rev_e4)
        self.assertEqual(info["diplotype"], "ε3/ε4")
        self.assertEqual(rec.category, "Carrier")

    def test_segregation_engine_recessive_carrier(self):
        from segregation_engine import SegregationEngine
        engine = SegregationEngine()

        # CFTR deltaF508 carrier (Autosomal Recessive)
        call = VariantCall("rs113993960", "7", 117199644, "DI", zygosity="het")
        rep = engine.analyze_variant_segregation(call, "CFTR", "Carrier", "Pathogenic (Carrier)")

        self.assertEqual(rep.mode_of_inheritance, "Autosomal Recessive")
        self.assertTrue(rep.is_carrier)
        self.assertFalse(rep.is_affected)
        # Partner carrier risk is 25% (1 in 4)
        self.assertEqual(rep.offspring_risk_carrier_partner, 0.25)
        # Prior with unscreened European partner (approx 4% * 0.25 = 1%)
        self.assertAlmostEqual(rep.offspring_risk_unscreened_partner, 0.01, places=2)
        self.assertEqual(len(rep.offspring_distribution), 3)

    def test_segregation_engine_dominant_transmission(self):
        from segregation_engine import SegregationEngine
        engine = SegregationEngine()

        # Factor V Leiden heterozygote (Autosomal Dominant)
        call = VariantCall("rs6025", "1", 169519049, "AG", zygosity="het")
        rep = engine.analyze_variant_segregation(call, "F5", "Risk Factor", "Pathogenic")

        self.assertIn("Dominant", rep.mode_of_inheritance)
        self.assertEqual(rep.offspring_risk_carrier_partner, 0.50)
        self.assertEqual(rep.penetrance, 0.10)
        self.assertEqual(len(rep.offspring_distribution), 2)

    def test_compound_heterozygosity_detection(self):
        from segregation_engine import SegregationEngine
        engine = SegregationEngine()

        # Patient with both HFE C282Y (rs1800562 AG) and HFE H63D (rs1799945 CG)
        variants = {
            "rs1800562": VariantCall("rs1800562", "6", 26093141, "AG", zygosity="het"),
            "rs1799945": VariantCall("rs1799945", "6", 26092913, "CG", zygosity="het"),
        }
        hits = engine.detect_compound_heterozygosity(variants)
        self.assertEqual(len(hits), 1)
        self.assertEqual(hits[0]["gene"], "HFE")
        self.assertIn("Compound Heterozygote", hits[0]["type"])
        self.assertIn("Trans Phasing", hits[0]["segregation_analysis"])

    def test_independent_assortment_multi_locus(self):
        from segregation_engine import SegregationEngine
        engine = SegregationEngine()

        # Dual Thrombophilia: F5 (Chr 1) and F2 (Chr 11)
        v_f5 = VariantCall("rs6025", "1", 169519049, "AG", zygosity="het")
        v_f2 = VariantCall("rs1799963", "11", 46761055, "AG", zygosity="het")

        rep_f5 = engine.analyze_variant_segregation(v_f5, "F5", "Risk Factor", "Pathogenic")
        rep_f2 = engine.analyze_variant_segregation(v_f2, "F2", "Risk Factor", "Pathogenic")

        multi = engine.evaluate_independent_assortment([rep_f5, rep_f2])
        self.assertEqual(len(multi), 1)
        self.assertTrue(multi[0].are_unlinked)
        # Joint probability = 0.50 * 0.50 = 0.25 (25%)
        self.assertEqual(multi[0].independent_transmission_prob, 0.25)
        self.assertIn("Thrombophilia", multi[0].combined_clinical_impact)

    def test_pedigree_simulation_scenarios(self):
        from segregation_engine import SegregationEngine
        engine = SegregationEngine()

        # Recessive condition (CFTR): simulation under tested carrier vs wildtype partner
        sim_carrier = engine.simulate_offspring_pedigree("CFTR", "DI", partner_status="carrier")
