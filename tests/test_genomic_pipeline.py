class TestKnowledgeBaseLoading(unittest.TestCase):
    def test_loader_accepts_the_committed_kb_and_annotator_defaults_to_it(self):
        kb = load_knowledge_base()
        self.assertGreater(len(kb.loci), 0)
        self.assertEqual(VariantAnnotator().kb.loci.keys(), kb.loci.keys())

    def test_loader_rejects_a_wrong_schema_version(self):
        data = pipeline_kb_json()
        data["schema_version"] = 1
        with self.assertRaises(KbSchemaError) as ctx:
            validate_kb(data)
        self.assertIn("schema_version", str(ctx.exception))

    def test_loader_fails_fast_on_a_missing_clinical_field_and_lists_every_problem(self):
        data = pipeline_kb_json()
        rsid = sorted(data["loci"])[0]
        del data["loci"][rsid]["interpretations"]["1"]["phenotype"]
        del data["loci"][rsid]["evidence_tier"]
        with self.assertRaises(KbSchemaError) as ctx:
            validate_kb(data)
        self.assertEqual(len(ctx.exception.problems), 2, ctx.exception.problems)

    def test_loader_rejects_per_sample_fields_in_the_kb(self):
        data = pipeline_kb_json()
        data["loci"][sorted(data["loci"])[0]]["coverage_state"] = "supported_and_observed"
        with self.assertRaises(KbSchemaError):
            validate_kb(data)

    def test_loader_rejects_duplicate_positions(self):
        data = pipeline_kb_json()
        a, b = sorted(data["loci"])[:2]
        data["loci"][b]["chrom"] = data["loci"][a]["chrom"]
        data["loci"][b]["pos_grch37"] = data["loci"][a]["pos_grch37"]
        with self.assertRaises(KbSchemaError):
            validate_kb(data)

    def test_loader_rejects_identical_ref_and_alt(self):
        data = pipeline_kb_json()
        locus = data["loci"][sorted(data["loci"])[0]]
        locus["alt"] = locus["ref"]
        with self.assertRaises(KbSchemaError) as ctx:
            validate_kb(data)
        self.assertIn("identical", str(ctx.exception))

    def test_loader_does_not_mutate_its_input(self):
        data = pipeline_kb_json()
        before = copy.deepcopy(data)
        validate_kb(data)
        self.assertEqual(data, before)

    def test_missing_kb_file_fails_fast_on_first_use_not_at_construction(self):
        annotator = VariantAnnotator(kb_path="/no/such/knowledge-base.json")
        with self.assertRaises(FileNotFoundError):
            annotator.annotate_genome(parse_genotype_file("# 23andMe\nrs1\t1\t5\tAA\n"))

    def test_constructors_do_no_filesystem_io(self):
        boom = AssertionError("filesystem touched in a constructor")
        with mock.patch.object(Path, "read_text", side_effect=boom), mock.patch.object(
            Path, "mkdir", side_effect=boom
        ), mock.patch.object(Path, "exists", side_effect=boom), mock.patch("builtins.open", side_effect=boom):
            annotator = VariantAnnotator()
            biotools_orchestrator.BiotoolsOrchestrator()
        self.assertIsNone(annotator._kb)
        self.assertIsNone(annotator._biotools)


class TestAnnotation(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.annotator = make_annotator()
        cls.kb = cls.annotator.kb

    def alleles(self, rsid, alt_count):
        locus = self.kb.loci[rsid]
        ref, alt = locus["ref"], locus["alt"]
        assert len(ref) == 1 and len(alt) == 1, rsid
        return {0: ref + ref, 1: ref + alt, 2: alt + alt}[alt_count]

    def file_text(self, genotypes, build="37"):
        rows = [f"# build {build}"]
        for rsid, value in genotypes.items():
            locus = self.kb.loci[rsid]
            gt = value if isinstance(value, str) else self.alleles(rsid, value)
            rows.append(f"{rsid}\t{locus['chrom']}\t{locus['pos_grch37']}\t{gt}")
        return "\n".join(rows) + "\n"

    def report(self, genotypes, build="37"):
        return self.annotator.annotate_genome(parse_genotype_file(self.file_text(genotypes, build)))

    def record(self, report, rsid):
        return next(r for r in report.records if r.rsid == rsid)

    def test_every_locus_is_listed_once_and_apoe_is_one_row(self):
        report = self.report({"rs1800562": 1})
        rsids = [r.rsid for r in report.records]
        self.assertEqual(len(rsids), len(set(rsids)))
        self.assertIn("APOE-STATUS", rsids)  # an internal row id, never shown by the views
        self.assertNotIn("rs429358", rsids)
        self.assertNotIn("rs7412", rsids)
        self.assertEqual(len(rsids), len(self.kb.loci) - 1)  # two components become one row
        self.assertEqual(report.coverage["total_loci"], len(rsids))

    def test_loci_absent_from_the_file_are_not_tested_never_clear(self):
        report = self.report({"rs1800562": 1})
        row = self.record(report, "rs3918290")
        self.assertEqual(row.coverage_state, "not_tested_by_array")
        self.assertEqual(row.sample_observation, "call_unavailable")
        self.assertEqual(row.genotype, "not tested")
        self.assertEqual(row.category, "Not available")
        self.assertIsNone(row.magnitude)
        self.assertIsNone(row.review_stars)
        self.assertIsNone(row.segregation)
        self.assertEqual(report.coverage["not_tested_by_array_count"], len(report.records) - 1)

    def test_apoe_e4_e4_is_an_e4_carrier_and_transmits_e4_with_probability_one(self):
        # PY-S7: the old code said e4/e4 was not a carrier with offspring risk 0.0.
        report = self.report({"rs429358": 2, "rs7412": 0})
        apoe = self.record(report, "APOE-STATUS")
        self.assertEqual(apoe.raw["diplotype"], "e4/e4")
        self.assertIn("ε4/ε4", apoe.genotype)
        self.assertTrue(apoe.segregation["e4_carrier"])
        self.assertEqual(apoe.segregation["scenarios"]["wildtype"]["inherits_allele"], 1)
        self.assertNotIn("affected", apoe.segregation["scenarios"]["wildtype"])
        self.assertEqual(apoe.sample_observation, "variant_present")

    def test_apoe_e2_e2_is_not_an_e4_carrier(self):
        report = self.report({"rs429358": 0, "rs7412": 2})
        apoe = self.record(report, "APOE-STATUS")
        self.assertEqual(apoe.raw["diplotype"], "e2/e2")
        self.assertFalse(apoe.segregation["e4_carrier"])

    def test_apoe_needs_both_components_and_never_presumes_e3(self):
        report = self.report({"rs429358": 0})
        apoe = self.record(report, "APOE-STATUS")
        self.assertIsNone(apoe.raw["diplotype"])
        self.assertEqual(apoe.coverage_state, "not_tested_by_array")
        self.assertIn("rs7412", apoe.reason)
        self.assertIsNone(apoe.segregation)

    def test_apoe_atypical_is_insufficient_evidence_with_no_interpretation(self):
        report = self.report({"rs429358": 2, "rs7412": 1})
        apoe = self.record(report, "APOE-STATUS")
        self.assertEqual(apoe.raw["diplotype"], "atypical")
        self.assertEqual(apoe.coverage_state, "insufficient_evidence")
        self.assertIsNone(apoe.raw["interpretation"])
        self.assertEqual(apoe.category, "Not available")

    def test_mendelian_het_is_a_carrier_and_a_wildtype_is_not(self):
        het = self.record(self.report({"rs1800562": 1}), "rs1800562")
        self.assertEqual(het.category, "Carrier")
        self.assertTrue(het.segregation["is_carrier"])
        self.assertFalse(het.segregation["is_affected"])
        self.assertTrue(het.acmg_actionable)
        wild = self.record(self.report({"rs1800562": 0}), "rs1800562")
        self.assertEqual(wild.coverage_state, "supported_not_observed")
        self.assertFalse(wild.segregation["is_carrier"])
        self.assertFalse(wild.segregation["is_affected"])

    def test_trait_gene_het_reports_transmission_only_never_recurrence(self):
        # PY-S2: the old MTHFR C677T het got "recurrence of severe deficiency" at 25% / 11%.
        row = self.record(self.report({"rs1801133": 1}), "rs1801133")
        self.assertTrue(row.variant_present)
        self.assertNotIn("is_carrier", row.segregation)
        self.assertNotIn("is_affected", row.segregation)
        for outcome in row.segregation["scenarios"].values():
            self.assertEqual(outcome["kind"], "transmission")
            self.assertNotIn("affected", outcome)
        # (`disease` carries the KB's own disclaimer that the severe condition is not what this SNP tests.)
        text = str(row.segregation["scenarios"]).lower()
        for banned in ("recurrence", "severe", "deficiency", "disease risk", "affected"):
            self.assertNotIn(banned, text)

    def test_unannotated_allele_in_a_recessive_gene_is_not_a_carrier(self):
        # PY-S3: any het of an allele outside the KB's ref/alt used to become "carrier" (CFTR 1%).
        locus = self.kb.loci["rs1800562"]
        row = self.record(self.report({"rs1800562": locus["ref"] + "D"}), "rs1800562")
        self.assertIsNone(row.alt_count)
        self.assertEqual(row.coverage_state, "insufficient_evidence")
        self.assertIsNone(row.segregation)
        self.assertEqual(row.reason, "genotype not interpretable")

    def test_wildtype_risk_factor_gene_has_no_affected_status(self):
        # S1 analogue: a wild-type F5 must not be "affected" with a 50% offspring risk.
        row = self.record(self.report({"rs6025": 0}), "rs6025")
        self.assertNotIn("is_affected", row.segregation)
        self.assertEqual(row.segregation["scenarios"]["wildtype"]["inherits_allele"], 0)

    def test_indel_array_codes_resolve_through_allele_codes(self):
        locus = self.kb.loci["rs113993960"]
        deleted = next(k for k, v in locus["allele_codes"].items() if v == "alt")
